/**
 * Catálogo de emojis do compositor do WhatsApp — dados + busca.
 *
 * Escrito à mão, e não puxado de uma biblioteca, por dois motivos práticos: o
 * pacote completo do Unicode passa de 1 MB só de metadados (entraria no bundle
 * do CRM inteiro para servir uma barra de mensagem), e as palavras-chave dele
 * vêm em inglês — quem atende digita "coracao", "obrigado", "risada".
 *
 * Cada item tem o caractere (`e`) e as palavras pelas quais ele é encontrado
 * (`k`), em português e sem acento: a busca também tira o acento do que foi
 * digitado, então "coração" e "coracao" acham a mesma coisa.
 *
 * Sem imports de propósito: módulo puro, para o ts-node do `npm test` carregá-lo
 * sem arrastar a cadeia do React (ver `testes-ts-node-imports`).
 */

export interface EmojiItem {
  /** O caractere em si. */
  e: string;
  /** Palavras-chave, separadas por espaço, minúsculas e sem acento. */
  k: string;
}

