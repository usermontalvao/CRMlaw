/** Todos os emojis, na ordem dos grupos — usado pela busca. */
export const TODOS_OS_EMOJIS: EmojiItem[] = GRUPOS_DE_EMOJI.flatMap(g => g.emojis);

/** Minúsculas e sem acento: é assim que a busca compara os dois lados. */
export function normalizarBusca(texto: string): string {
  return texto
    .toLocaleLowerCase('pt-BR')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Emojis que casam com o termo digitado.
 *
 * O casamento é por INÍCIO DE PALAVRA, não por trecho solto: "paz" encontrar
 * "capaz" faria a busca devolver justamente o que não se procurava. Com termo
 * vazio devolve nada — quem manda na tela nesse caso é o grupo selecionado.
 */
export function buscarEmojis(termo: string, limite = 60): EmojiItem[] {
  const alvo = normalizarBusca(termo);
  if (!alvo) return [];
  const achados: EmojiItem[] = [];
  for (const item of TODOS_OS_EMOJIS) {
    const casa = item.k.split(' ').some(palavra => palavra.startsWith(alvo));
    if (!casa) continue;
    achados.push(item);
    if (achados.length >= limite) break;
  }
  return achados;
}
